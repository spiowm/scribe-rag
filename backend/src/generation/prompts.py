def user_context(member: dict | None) -> str:
    """Блок про співрозмовника для системного промпта."""
    if member is None:
        return (
            "## З ким ти говориш\n\n"
            "Співрозмовника не впізнано в довіднику. Не вигадуй, хто він, і не "
            "питай номер — доступ до бота вже підтверджений. На питання про "
            "«мене» проси уточнити імʼя."
        )

    name = f"{member.get('first_name', '')} {member.get('last_name', '')}".strip()
    rows = [f"- Імʼя: **{name}**"]
    if member.get("status"):
        rows.append(f"- Статус: {member['status']}")
    current = member.get("current_positions") or []
    if current:
        rows.append(f"- Поточні посади (за інфобуком): {'; '.join(current)}")
    past = member.get("past_positions") or []
    if past:
        # Посади йдуть хронологічно, і бордівська зазвичай наприкінці: заміряно,
        # у перших шести вона лише в 11 людей із 27, в останніх — у 21. Тому
        # бордівські показуємо завжди, а решту місць віддаємо найсвіжішим.
        board_kw = ("president", "treasurer", "secretary", "vp4")
        board = [x for x in past if any(k in x.lower() for k in board_kw)]
        recent = [x for x in reversed(past) if x not in board]
        shown = board + recent[: max(0, 6 - len(board))]
        hidden = len(past) - len(shown)
        tail = f" (і ще {hidden})" if hidden else ""
        rows.append(f"- Попередні посади: {'; '.join(shown)}{tail}")
    # Вступні факти йдуть у хвіст: коли вони стояли вгорі, модель дзеркалила
    # порядок і починала розповідь про людину з родини та ангела.
    since = member.get("member_since")
    if since:
        rows.append(f"- В осередку з: {str(since)[:10]}")
    if member.get("family"):
        rows.append(f"- Родина: {member['family']}")
    if member.get("mentor_name"):
        rows.append(f"- Ангел (ментор): {member['mentor_name']}")
    profile = "\n".join(rows)

    return (
        "## З ким ти говориш\n\n"
        f"{profile}\n\n"
        "Як цим користуватись:\n"
        "- Звертайся на імʼя, коли це природно. Не в кожному реченні.\n"
        "- Це фон для калібрування відповіді, а не те, що треба зачитувати. "
        "Не переказуй людині її ж профіль без запиту.\n"
        "- Питання про себе — «хто мій ангел», «які в мене посади», «у якій я "
        "родині», «коли я вступив» — відповідай звідси, не питаючи, хто він. "
        "Посади тут урізані («і ще N»): на питання саме про посади візьми "
        "повний список через `find_person` за імʼям людини.\n"
        "- Статус підказує, що людині потрібно: обзерверу на «як стати фулом» "
        "потрібен шлях для нього самого, а бордівцю на те саме питання — "
        "найпевніше процедура для когось іншого.\n"
        "- **Якщо людина каже, що в профілі помилка — права вона.** Довідник "
        "відстає: статуси й активність оновлюють не щодня. Не спорь із людиною "
        "про її власні дані й не наполягай на тому, що тут написано.\n"
        "- Не додумуй, чого людина не знає, за межами очевидного зі статусу."
    )


def drive_context(facts) -> str:
    """Блок про диски співрозмовника: що підключено, до чого є доступ і чому,
    що вимкнено. `facts` — `access.DriveFacts`."""

    def names(ids) -> str:
        return ", ".join(facts.connected[d] for d in ids)

    def with_reasons(ids) -> str:
        return ", ".join(
            f"{facts.connected[d]} ({'; '.join(facts.reasons[d])})" for d in ids
        )

    rows = [
        "- Загальна база — Notion і загальний диск: її бачать усі, вимкнути не можна."
    ]
    if facts.connected:
        rows.append(f"- Диски, підключені до бота: {names(facts.connected)}.")
        off = [d for d in facts.connected if d in facts.off]
        closed = [d for d in facts.connected if d not in facts.reasons]
        if not facts.recognized:
            rows.append("- Співрозмовника не впізнано в довіднику: з дисків — жодного.")
        elif not facts.reasons:
            rows.append("- Доступу до жодного з них у цієї людини немає.")
        else:
            if facts.enabled:
                rows.append(
                    f"- Увімкнені, шукаєш і тут: {with_reasons(facts.enabled)}."
                )
            if off:
                rows.append(
                    "- Доступ є, але вимкнені в /drives — тут не шукаєш: "
                    f"{with_reasons(off)}."
                )
            if closed:
                rows.append(f"- Без доступу: {names(closed)}.")
    else:
        rows.append("- Інших дисків до бота поки не підключено.")

    return (
        "## Де ти шукаєш\n\n"
        "Пошук сам обмежений тим, що бачить ця людина:\n"
        + "\n".join(rows)
        + "\n\nЯк цим користуватись:\n"
        "- Питають, до чого в тебе доступ, які диски чи де ти шукаєш, — відповідай "
        "звідси. Це твій справжній доступ, а не «лише індекс бази».\n"
        "- Доступ до диска — той самий, що в людини в Google Drive: його дає група "
        "диска (у дужках — через що саме). Додати доступ бот не може.\n"
        "- Увімкнути чи вимкнути доступний диск — командою /drives у боті. Не "
        "знайшов, а питання явно про тему вимкненого диска (CTF — про CTF), — "
        "скажи, що цей диск вимкнений, і підкажи /drives."
    )
