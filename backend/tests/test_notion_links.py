from src.generation.tools import absolute_notion_links

BASE = "https://app.notion.com/p/"


def test_p_form_keeps_query_and_block():
    src = "[Сторінка прикладу 1](/p/11111111111141118111000000000001?pvs=25#11111111111141118111000000000002)"
    assert absolute_notion_links(src) == (
        f"[Сторінка прикладу 1]({BASE}11111111111141118111000000000001"
        "?pvs=25#11111111111141118111000000000002)"
    )


def test_bare_id_gets_p_prefix():
    # `app.notion.com/<id>` без `/p/` не відкривається
    src = (
        "[Сторінка прикладу 2](/11111111111141118111000000000003#11111111111141118111000000000004), "
        "[Зразок із параметром](/11111111111141118111000000000005?pvs=25), "
        "[**Зразок форматування**](/11111111111141118111000000000006)"
    )
    assert absolute_notion_links(src) == (
        f"[Сторінка прикладу 2]({BASE}11111111111141118111000000000003#11111111111141118111000000000004), "
        f"[Зразок із параметром]({BASE}11111111111141118111000000000005?pvs=25), "
        f"[**Зразок форматування**]({BASE}11111111111141118111000000000006)"
    )


def test_database_view_kept():
    src = "[база](/11111111111141118111000000000007?v=11111111111141118111000000000008&pvs=25)"
    assert absolute_notion_links(src) == (
        f"[база]({BASE}11111111111141118111000000000007?v=11111111111141118111000000000008&pvs=25)"
    )


def test_other_links_untouched():
    src = (
        "[**Абсолютне посилання**](https://www.notion.so/fixture/"
        "Synthetic-Page-11111111111141118111000000000009) "
        f'<page url="{BASE}11111111111141118111000000000010">Корисні</page> '
        "[пошта](mailto:fixture@example.test) [демо](./docs/demo.gif) "
        "[x](/docs/readme) шлях /11111111111141118111000000000003 поза посиланням"
    )
    assert absolute_notion_links(src) == src
